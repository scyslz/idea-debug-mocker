package com.debugmock.ui;

import com.debugmock.compile.BlockCompiler;
import com.debugmock.json.JsonExample;
import com.debugmock.model.MockAction;
import com.debugmock.model.MockRule;
import com.debugmock.psi.ExecutionContext;
import com.debugmock.psi.MethodInfo;
import com.debugmock.store.MockRuleStore;
import com.intellij.openapi.application.ReadAction;
import com.intellij.openapi.project.Project;
import com.intellij.openapi.ui.DialogWrapper;
import com.intellij.ui.components.JBLabel;
import com.intellij.util.ui.FormBuilder;
import com.intellij.util.ui.JBUI;
import org.jetbrains.annotations.Nullable;

import javax.swing.JButton;
import javax.swing.JCheckBox;
import javax.swing.JComboBox;
import javax.swing.JComponent;
import javax.swing.JPanel;
import javax.swing.JTextField;
import java.awt.BorderLayout;

/**
 * Dialog for creating / editing a mock rule. Two Java code editors (Condition and Value/Statement)
 * keep a fixed width and can be expanded; switching the Action only changes the placeholder, never
 * the control layout. All value semantics are expressed as real Java code compiled by the IDE.
 */
public class AddMockRuleDialog extends DialogWrapper {

    private final MethodInfo methodInfo;
    private final MockRule existing;
    private final Project project;

    private final JComboBox<MockAction> actionCombo = new JComboBox<>(MockAction.values());
    private final ExpandableCodeField conditionField;
    private final ExpandableCodeField valueField;
    private final JCheckBox enabledBox = new JCheckBox("Enabled", true);
    private final JButton jsonButton = new JButton("JSON");
    private JBLabel hintLabel;

    private final int lineNumber;
    private final MockAction preselectedAction;

    private BlockCompiler.CompiledBlock compiledBlock;
    /** True when the RETURN value is raw JSON and should be deserialized by the agent's Gson. */
    private boolean rawJsonReturn;
    /**
     * Set when a RETURN value is a plain Java literal. The agent can return such a value directly
     * from its generated bytecode, so no javac run is needed — exactly like the JSON path.
     */
    private String constantReturnValue;

    public AddMockRuleDialog(Project project, MethodInfo methodInfo, @Nullable MockRule existing) {
        this(project, methodInfo, existing, null, initialLine(existing, methodInfo));
    }

    /**
     * The stored line of an existing rule may be stale (a line above it was deleted). Resolve it
     * against the rule's anchor first, so the dialog and the compiled block target the same code.
     */
    private static int initialLine(@Nullable MockRule existing, MethodInfo methodInfo) {
        if (existing == null) {
            return methodInfo.getLineNumber();
        }
        if (existing.getLineNumber() <= 0) {
            return existing.getLineNumber();
        }
        return ReadAction.compute(() -> com.debugmock.psi.RuleLines.resolve(existing, methodInfo.getMethod()));
    }

    /** Creates a dialog with a preselected action and a fixed source line (for Add Execute). */
    public AddMockRuleDialog(Project project, MethodInfo methodInfo, MockAction preselectedAction, int lineNumber) {
        this(project, methodInfo, null, preselectedAction, lineNumber);
    }

    private AddMockRuleDialog(Project project, MethodInfo methodInfo, @Nullable MockRule existing,
                              MockAction preselectedAction, int lineNumber) {
        super(project, true);
        this.methodInfo = methodInfo;
        this.existing = existing;
        this.project = project;
        this.preselectedAction = preselectedAction;
        this.lineNumber = lineNumber;

        // Both factories read PSI to build the editor's code-fragment context; the dialog is
        // constructed on the EDT, so those reads must run inside a read action.
        conditionField = new ExpandableCodeField(project, ReadAction.compute(() ->
                StatementEditorUtil.createCondition(project, methodInfo,
                        existing == null ? "" : existing.getCondition(), lineNumber)));
        valueField = new ExpandableCodeField(project, ReadAction.compute(() ->
                StatementEditorUtil.createBlock(project, methodInfo, initialValue(), lineNumber)));

        setTitle(existing == null ? "Add Mock Rule" : "Edit Mock Rule");
        setOKButtonText(existing == null ? "Create" : "Save");
        enabledBox.setSelected(existing == null || existing.isEnabled());
        init();
    }

    @Override
    protected @Nullable JComponent createCenterPanel() {
        JTextField classField = readOnlyField(methodInfo.getClassName());
        JTextField methodField = readOnlyField(methodInfo.getMethodName() + "()");
        JTextField signatureField = readOnlyField(methodInfo.getSignature());
        JTextField lineField = readOnlyField(lineNumber > 0
                ? String.valueOf(lineNumber) : "0  (method entry)");

        // Only SKIP is excluded for non-void; everything else is a Java block.
        if (!methodInfo.isVoidReturn()) {
            actionCombo.removeItem(MockAction.SKIP);
        }
        MockAction initial = preselectedAction != null ? preselectedAction
                : existing != null ? existing.getAction()
                : (methodInfo.isVoidReturn() ? MockAction.SKIP : MockAction.RETURN);
        if (initial != null) {
            actionCombo.setSelectedItem(initial);
        }
        updatePlaceholder();
        actionCombo.addActionListener(e -> updatePlaceholder());

        conditionField.setPlaceholder("Optional Java boolean expression, e.g. name != null && id > 5");
        jsonButton.setToolTipText("Insert a JSON skeleton of the return type, then fill in the values");
        jsonButton.addActionListener(e -> insertJsonSkeleton());
        // North-anchored so the button keeps its own height when the editor is expanded.
        JPanel jsonHolder = new JPanel(new BorderLayout());
        jsonHolder.setOpaque(false);
        jsonHolder.add(jsonButton, BorderLayout.NORTH);
        JPanel valueRow = new JPanel(new BorderLayout(4, 0));
        valueRow.add(valueField, BorderLayout.CENTER);
        valueRow.add(jsonHolder, BorderLayout.EAST);

        FormBuilder builder = FormBuilder.createFormBuilder();
        builder.addLabeledComponent("Class", classField);
        builder.addLabeledComponent("Method", methodField);
        builder.addLabeledComponent("Signature", signatureField);
        builder.addLabeledComponent("Line", lineField);
        builder.addLabeledComponent("Condition", conditionField);
        builder.addLabeledComponent("Action", actionCombo);
        builder.addLabeledComponent("Value / Code", valueRow);
        hintLabel = hint(hintText());
        builder.addComponent(hintLabel);
        builder.addComponent(bottomRow());
        return builder.getPanel();
    }

    /** Enabled switch for every rule; Delete only when editing an existing rule. */
    private JPanel bottomRow() {
        JPanel row = new JPanel(new BorderLayout(8, 0));
        row.add(enabledBox, BorderLayout.WEST);
        if (existing != null) {
            JButton delete = new JButton("Delete");
            delete.setToolTipText("Delete this rule");
            delete.addActionListener(e -> {
                MockRuleStore.getInstance().remove(project, existing);
                close(CANCEL_EXIT_CODE);
            });
            row.add(delete, BorderLayout.EAST);
        }
        return row;
    }

    /** Replaces the field content with a JSON skeleton of the method's return type. */
    private void insertJsonSkeleton() {
        try {
            String json = ReadAction.compute(() -> JsonExample.forType(
                    methodInfo.getMethod().getReturnType(), methodInfo.getClassName()));
            valueField.setText(json);
        } catch (RuntimeException e) {
            setErrorText("Cannot generate a JSON example: " + e.getMessage());
        }
    }

    private static JBLabel hint(String text) {
        JBLabel label = new JBLabel(text);
        label.setFont(JBUI.Fonts.smallFont());
        label.setForeground(JBUI.CurrentTheme.ContextHelp.FOREGROUND);
        return label;
    }

    /** Switching Action changes only the hint, not the editor control. */
    private void updatePlaceholder() {
        MockAction action = (MockAction) actionCombo.getSelectedItem();
        if (action == MockAction.SKIP) {
            valueField.setPlaceholder("No value — the original method body is skipped.");
        } else if (action == MockAction.THROW) {
            valueField.setPlaceholder("Java expression, e.g.  new BizException(\"invalid id\")   (you may also write the full throw statement)");
        } else if (action == MockAction.EXECUTE) {
            valueField.setPlaceholder("Java code block, e.g.  System.out.println(name); return \"done\";");
        } else {
            valueField.setPlaceholder("Java value or JSON, e.g.  \"mock-name\"  /  42  /  { \"id\": 1 }  /  return \"x\";");
        }
        boolean jsonExample = action == MockAction.RETURN && supportsJsonExample();
        jsonButton.setVisible(jsonExample);
        if (hintLabel != null) {
            hintLabel.setText(hintText());
        }
    }

    /** Variables in scope, plus a note when a JSON example can be used for the value. */
    private String hintText() {
        String available = "Available: " + ReadAction.compute(() -> ExecutionContext.of(methodInfo,
                com.debugmock.psi.LocalVariables.inScope(methodInfo.getMethod(), lineNumber))
                .variablesHint());
        if (actionCombo.getSelectedItem() == MockAction.RETURN && supportsJsonExample()) {
            return available + "   ·   JSON is turned into Java on save";
        }
        return available;
    }

    /** True when a RETURN value is a JSON object/array for a structured return type. */
    private boolean isJsonReturn(MockAction action, String code) {
        if (action != MockAction.RETURN || code.isEmpty()) {
            return false;
        }
        String value = code.trim();
        if (!value.startsWith("{") && !value.startsWith("[")) {
            return false;
        }
        return supportsJsonExample();
    }

    /** True when the return type is an object whose JSON skeleton can be generated. */
    private boolean supportsJsonExample() {
        try {
            return ReadAction.compute(() -> JsonExample.supports(
                    methodInfo.getMethod().getReturnType()));
        } catch (RuntimeException e) {
            return false;
        }
    }

    private String initialValue() {
        if (existing == null) {
            return "";
        }
        if (existing.getStatement() != null && !existing.getStatement().isEmpty()) {
            return existing.getStatement();
        }
        if (existing.getAction() == MockAction.THROW) {
            if (existing.getExceptionClass() != null) {
                String message = existing.getExceptionMessage() == null ? "" : existing.getExceptionMessage();
                return "new " + existing.getExceptionClass() + "(\"" + message + "\")";
            }
        }
        return existing.getReturnValue() == null ? "" : existing.getReturnValue();
    }

    @Override
    protected void doOKAction() {
        MockAction action = (MockAction) actionCombo.getSelectedItem();
        String code = valueField.getText().trim();

        rawJsonReturn = isJsonReturn(action, code);
        constantReturnValue = null;
        if (action == MockAction.SKIP || rawJsonReturn) {
            // A JSON object/array for a structured return type is deserialized at runtime by the
            // agent's Gson (MockValues.fromJson). No Java compilation needed — Gson already handles
            // private fields, Lombok @Data, extra keys, string numbers and ISO dates.
            compiledBlock = null;
        } else if (code.isEmpty()) {
            setErrorText("Value / code is required", valueField.getField());
            return;
        } else if ((constantReturnValue = constantLiteral(action, code)) != null) {
            // A constant string / number / boolean needs no compilation either: the agent emits an
            // LDC / iconst for it. This used to launch javac on the EDT and froze the UI for seconds.
            compiledBlock = null;
        } else {
            // javac is slow and it reads PSI (return type, locals, imports), so run it off the EDT
            // under a progress indicator and hold a read action for the PSI reads. Running it on the
            // EDT made the dialog appear hung and produced ThreadingAssertions errors on 2026.3+.
            BlockCompiler.CompiledBlock[] compiled = new BlockCompiler.CompiledBlock[1];
            String[] failure = new String[1];
            com.intellij.openapi.progress.ProgressManager.getInstance()
                    .runProcessWithProgressSynchronously(() -> {
                        try {
                            compiled[0] = ReadAction.compute(() ->
                                    BlockCompiler.compileForAction(code, action, project,
                                            methodInfo, lineNumber));
                        } catch (BlockCompiler.CompileException e) {
                            failure[0] = e.getMessage();
                        }
                    }, "Compiling mock rule", false, project);
            if (failure[0] != null) {
                setErrorText(failure[0]);
                return;
            }
            compiledBlock = compiled[0];
        }
        setErrorText(null);
        super.doOKAction();
    }

    /**
     * Returns the value the agent can return directly for a Java literal, or {@code null} when the
     * value needs the full compiler. Only the two most common constant cases are handled here: a
     * string literal for a {@code String} return type, and a number / boolean literal for a
     * primitive return type. Everything else (expressions, blocks, object types) is compiled as
     * before.
     */
    private String constantLiteral(MockAction action, String code) {
        if (action != MockAction.RETURN) {
            return null;
        }
        String descriptor = methodInfo.getReturnType();
        if (descriptor == null) {
            return null;
        }
        String raw = code.trim();
        if (raw.length() >= 2 && raw.charAt(0) == '"' && raw.charAt(raw.length() - 1) == '"') {
            if (!"Ljava/lang/String;".equals(descriptor)) {
                return null;
            }
            String body = raw.substring(1, raw.length() - 1);
            // Reject concatenations like "a" + "b": their body contains an unescaped quote.
            for (int i = 0; i < body.length(); i++) {
                if (body.charAt(i) == '"' && (i == 0 || body.charAt(i - 1) != '\\')) {
                    return null;
                }
            }
            return unescapeJava(body);
        }
        if (isPrimitiveLiteral(raw)) {
            switch (descriptor) {
                case "Z": case "B": case "S": case "I": case "J": case "F": case "D":
                    return raw;
                default:
                    return null;
            }
        }
        return null;
    }

    private static boolean isPrimitiveLiteral(String raw) {
        if ("true".equals(raw) || "false".equals(raw)) {
            return true;
        }
        if (raw.isEmpty()) {
            return false;
        }
        int start = (raw.charAt(0) == '-' || raw.charAt(0) == '+') ? 1 : 0;
        if (start >= raw.length()) {
            return false;
        }
        boolean digit = false;
        for (int i = start; i < raw.length(); i++) {
            char c = raw.charAt(i);
            if (Character.isDigit(c)) {
                digit = true;
            } else if (c != '.' && c != 'e' && c != 'E' && c != '+') {
                // No Java suffixes / underscores: parseInt/parseLong would choke on them.
                return false;
            }
        }
        return digit;
    }

    /** Decodes the Java escapes javac would have applied to a string literal. */
    private static String unescapeJava(String body) {
        StringBuilder sb = new StringBuilder(body.length());
        for (int i = 0; i < body.length(); i++) {
            char c = body.charAt(i);
            if (c != '\\' || i + 1 >= body.length()) {
                sb.append(c);
                continue;
            }
            char next = body.charAt(++i);
            switch (next) {
                case 'n': sb.append('\n'); break;
                case 'r': sb.append('\r'); break;
                case 't': sb.append('\t'); break;
                case 'b': sb.append('\b'); break;
                case 'f': sb.append('\f'); break;
                default: sb.append(next); break;
            }
        }
        return sb.toString();
    }

    public MockRule buildRule() {
        MockRule rule = existing == null
                ? new MockRule(methodInfo.getClassName(), methodInfo.getMethodName(),
                        methodInfo.getSignature(), methodInfo.getReturnType())
                : copyOf(existing);

        MockAction action = (MockAction) actionCombo.getSelectedItem();
        rule.setAction(action);
        rule.setEnabled(enabledBox.isSelected());
        rule.setCondition(conditionField.getText().trim());
        rule.setLineNumber(lineNumber);
        // Bind the rule to the statement text, not only to the line number: rules then follow
        // their code when lines above are inserted / deleted (like debugger breakpoints).
        if (lineNumber > 0) {
            rule.setLineAnchor(ReadAction.compute(() ->
                    com.debugmock.psi.RuleLines.anchorFor(methodInfo.getMethod(), lineNumber)));
            rule.setLineOrdinal(ReadAction.compute(() ->
                    com.debugmock.psi.RuleLines.ordinalFor(methodInfo.getMethod(), lineNumber)));
        } else {
            rule.setLineAnchor(null);
            rule.setLineOrdinal(-1);
        }
        // MethodInfo's strings are cached, but these two calls traverse the live PSI tree.
        String[] parameterNames = ReadAction.compute(methodInfo::getParameterNames);
        java.util.List<com.debugmock.psi.LocalVariables.Local> locals = ReadAction.compute(() ->
                com.debugmock.psi.LocalVariables.inScope(methodInfo.getMethod(), lineNumber));
        rule.setParameterNames(parameterNames);
        String[] localNames = new String[locals.size()];
        String[] localTypes = new String[locals.size()];
        for (int i = 0; i < locals.size(); i++) {
            localNames[i] = locals.get(i).name;
            localTypes[i] = locals.get(i).descriptor;
        }
        rule.setLocalNames(localNames);
        rule.setLocalTypes(localTypes);

        String code = valueField.getText().trim();
        boolean directReturn = rawJsonReturn || constantReturnValue != null;
        rule.setStatement(directReturn ? null : code);
        // Raw JSON or a constant literal is handed to the agent, which returns it without running
        // a compiled block (Gson deserializes JSON, constants are emitted directly in bytecode).
        rule.setReturnValue(directReturn ? (rawJsonReturn ? code : constantReturnValue) : null);
        rule.setExceptionClass(null);
        rule.setExceptionMessage(null);
        rule.setCompiledBytecode(compiledBlock == null ? null : compiledBlock.base64);
        rule.setCompiledSource(compiledBlock == null ? null : compiledBlock.source);
        rule.setCompiledClassName(compiledBlock == null ? null : compiledBlock.className);
        rule.setCompiledTerminates(compiledBlock == null || compiledBlock.terminates);
        rule.setUpdatedAt(System.currentTimeMillis());
        return rule;
    }

    private static MockRule copyOf(MockRule source) {
        MockRule copy = new MockRule(source.getClassName(), source.getMethodName(),
                source.getSignature(), source.getReturnType());
        copy.setId(source.getId());
        copy.setCreatedAt(source.getCreatedAt());
        copy.setEnabled(source.isEnabled());
        return copy;
    }

    private static JTextField readOnlyField(String text) {
        JTextField field = new JTextField(text);
        field.setEditable(false);
        field.setFocusable(false);
        return field;
    }

    /** Shows the dialog and returns the configured rule, or null if cancelled. */
    public static MockRule show(Project project, MethodInfo info, MockRule existing) {
        AddMockRuleDialog dialog = new AddMockRuleDialog(project, info, existing);
        if (!dialog.showAndGet()) {
            return null;
        }
        return dialog.buildRule();
    }

    /** Shows the dialog with EXECUTE preselected and the given source line locked in. */
    public static MockRule showExecute(Project project, MethodInfo info, int lineNumber) {
        AddMockRuleDialog dialog = new AddMockRuleDialog(project, info, MockAction.EXECUTE, lineNumber);
        if (!dialog.showAndGet()) {
            return null;
        }
        return dialog.buildRule();
    }
}
